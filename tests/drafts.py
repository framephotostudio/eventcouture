# Save-and-finish-later, name ideas and rename. python3 tests/drafts.py outdir
import sys, os
from playwright.sync_api import sync_playwright
OUT = sys.argv[1]; HERE = os.path.dirname(os.path.abspath(__file__)); problems = []
with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_page(viewport={'width': 390, 'height': 844})
    errs = []; pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto('http://localhost:8765/#/new'); pg.wait_for_selector('#files')
    pg.set_input_files('#files', [os.path.join(HERE, 'pink.jpg')]); pg.wait_for_selector('.photo img')
    pg.click('[data-vibe="Gold"]'); pg.click('[data-vibe="Romantic"]')
    pg.click('#next'); pg.wait_for_selector('#names .chip')
    pg.select_option('#type', 'wedding'); pg.wait_for_timeout(100)
    ideas = pg.locator('#names .chip').all_inner_texts()
    pg.click('#names .chip >> nth=1'); name = pg.input_value('#name')
    pg.fill('#guests', '150'); pg.fill('#expected', '140')
    pg.screenshot(path=OUT + '/draft-step2.png', full_page=True)
    pg.click('#later'); pg.wait_for_selector('text=In progress')
    pg.screenshot(path=OUT + '/draft-events.png', full_page=True)
    if name not in pg.inner_text('#main'): problems.append('draft name not listed')
    pg.reload(); pg.wait_for_selector('text=In progress')
    pg.click('text=Continue'); pg.wait_for_selector('#name')
    if pg.input_value('#name') != name or pg.input_value('#guests') != '150': problems.append('draft details lost')
    pg.select_option('#city', 'Houston, TX'); pg.click('#setting [data-v=indoor]'); pg.click('#next'); pg.click('#go'); pg.wait_for_selector('.concept'); pg.click('.concept button.gold'); pg.wait_for_selector('#rename')
    pg.click('#rename'); pg.fill('#nn', 'Our Forever Day'); pg.click('#ok'); pg.wait_for_timeout(200)
    if 'Our Forever Day' not in pg.inner_text('.plan-head'): problems.append('rename failed')
    pg.goto('http://localhost:8765/#/events'); pg.wait_for_timeout(200)
    if 'In progress' in pg.inner_text('#main'): problems.append('paid draft still listed as in progress')
    print('ideas:', ideas)
    if errs: problems.append(errs)
    b.close()
print(problems or 'drafts ok')
